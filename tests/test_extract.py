import re

import pytest

from outreach.config import Settings
from outreach.models import DomainRelation, ExtractMethod
from outreach.research.extract import (
    ExtractConfig,
    cf_decode,
    cf_encode,
    extract_page,
    normalize_for_match,
    parse,
    quote_found,
    visible_text,
)
from tests.conftest import load_profile
from tests.sites import site_page


@pytest.fixture
def cfg(settings: Settings) -> ExtractConfig:
    return ExtractConfig.from_profile(load_profile(), settings)


def page(domain: str, path: str = "/") -> str:
    html = site_page(domain, path)
    assert html is not None
    return html


def by_method(found: list, method: ExtractMethod) -> set[str]:
    return {e.address_norm for e in found if e.method == method}


def test_each_method_on_the_acme_contact_page(cfg: ExtractConfig) -> None:
    out = extract_page(page("acme-roofing.test", "/contact"), "https://acme-roofing.test/contact",
                       "acme-roofing.test", cfg)
    assert by_method(out.emails, ExtractMethod.mailto) == {"jim@acme-roofing.test"}
    assert by_method(out.emails, ExtractMethod.visible_text) == {"info@acme-roofing.test"}
    assert by_method(out.emails, ExtractMethod.text_obfuscated) == {"office@acme-roofing.test"}
    assert all(e.domain_relation == DomainRelation.same_domain for e in out.emails)
    assert out.contact_form_url == "https://acme-roofing.test/send"
    assert out.phones == ["+15205550142"]
    assert out.us_evidence == "address:AZ 85705"


def test_hidden_text_and_junk_never_extracted(cfg: ExtractConfig) -> None:
    out = extract_page(page("acme-roofing.test", "/contact"), "https://acme-roofing.test/contact",
                       "acme-roofing.test", cfg)
    addresses = {e.address_norm for e in out.emails}
    assert "hidden@acme-roofing.test" not in addresses  # display:none
    assert not any(a.endswith(".png") for a in addresses)  # logo@2x.png
    assert "example@example.com" not in addresses  # placeholder
    assert not any("sentry" in a for a in addresses)  # inside <script>, and a vendor domain


def test_jsonld_address_is_us_evidence_and_widget_is_a_marker(cfg: ExtractConfig) -> None:
    out = extract_page(page("acme-roofing.test"), "https://acme-roofing.test/", "acme-roofing.test", cfg)
    assert out.jsonld_addresses == ["120 W Speedway Blvd, Tucson, AZ, 85705"]
    assert out.us_evidence is not None and out.us_evidence.startswith("address:120 W Speedway")
    assert out.markers == ["Tidio"]


