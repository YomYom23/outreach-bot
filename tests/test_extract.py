def test_gmail_on_own_site_is_freemail(cfg: ExtractConfig) -> None:
    out = extract_page(page("ortega-roofing.test", "/contact"), "https://ortega-roofing.test/contact",
                       "ortega-roofing.test", cfg)
    [email] = out.emails
    assert email.address_norm == "maria.ortega.roofing@gmail.com"
    assert email.domain_relation == DomainRelation.freemail
    assert "Email Maria" in email.context
    assert out.us_evidence == "phone:+15125550133"


def test_cloudflare_round_trip() -> None:
    for address, key in [("sam@cf-roofing.test", 0x3C), ("a.b+c@x.test", 0x00), ("o@x.test", 0xFF)]:
        assert cf_decode(cf_encode(address, key)) == address
    assert cf_decode("zz") is None and cf_decode("41") is None


def test_cloudflare_span_and_link_forms(cfg: ExtractConfig) -> None:
    html = page("cf-roofing.test", "/contact")
    # The fixture was generated by cf_encode; the page itself must not show the plain addresses.
    assert "sam@cf-roofing.test" not in html and re.search(r'data-cfemail="[0-9a-f]+"', html)
    out = extract_page(html, "https://cf-roofing.test/contact", "cf-roofing.test", cfg)
    assert by_method(out.emails, ExtractMethod.cf_decoded) == {"sam@cf-roofing.test", "estimates@cf-roofing.test"}


def test_other_domain_relation(cfg: ExtractConfig) -> None:
    html = "<html><body><p>Write to bob@builder-supply.test or rick@roofer.test.</p></body></html>"
    out = extract_page(html, "https://roofer.test/", "roofer.test", cfg)
    relations = {e.address_norm: e.domain_relation for e in out.emails}
    assert relations == {"bob@builder-supply.test": DomainRelation.other_domain,
                         "rick@roofer.test": DomainRelation.same_domain}


def test_visible_text_drops_scripts_styles_and_hidden() -> None:
    html = ("<html><head><style>p{}</style></head><body><p>Shown</p><script>x()</script><div hidden>A</div>"
            "<span aria-hidden='true'>B</span><p style='visibility: hidden'>C</p><p>Also shown</p></body></html>")
    assert visible_text(parse(html)) == "Shown Also shown"


def test_quote_matching_normalization() -> None:
    page_text = "Jim Carter,  owner of “Acme” Roofing​"
    assert normalize_for_match(page_text) == 'jim carter, owner of "acme" roofing'
    assert quote_found('JIM CARTER, owner of "Acme" Roofing', [page_text])
    assert not quote_found("Bob Smith, owner", [page_text])
    assert not quote_found("", [page_text]) and not quote_found(None, [page_text])
